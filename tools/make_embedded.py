#!/usr/bin/env python3
# Bundles the painting textures, fonts and the dissolve mask as data URIs so the site also looks right
# when index.html is opened straight from the computer (file://), where browsers block WebGL textures,
# web fonts and CSS masks from reading local files.
import base64, pathlib
site = pathlib.Path(__file__).resolve().parent.parent   # the website folder
def uri(rel, mime):
    return 'data:%s;base64,%s' % (mime, base64.b64encode((site / rel).read_bytes()).decode())
tex = {
    'painting': uri('assets/painting/painting-1280.webp', 'image/webp'),
    'sky': uri('assets/painting/flow-sky.png', 'image/png'),
    'sea': uri('assets/painting/flow-sea.png', 'image/png'),
    'mask': uri('assets/painting/masks.png', 'image/png'),
    'noise': uri('assets/painting/noise.png', 'image/png'),
    'blur': uri('assets/painting/painting-blur.jpg', 'image/jpeg'),
}
fonts = [
    ('Fraunces', 'assets/fonts/fraunces-var.woff2', '100 900', 'normal'),
    ('Fraunces', 'assets/fonts/fraunces-var-italic.woff2', '100 900', 'italic'),
    ('Instrument Sans', 'assets/fonts/instrument-sans-400.woff2', '400', 'normal'),
    ('Instrument Sans', 'assets/fonts/instrument-sans-400-italic.woff2', '400', 'italic'),
    ('Instrument Sans', 'assets/fonts/instrument-sans-500.woff2', '500', 'normal'),
    ('Instrument Sans', 'assets/fonts/instrument-sans-600.woff2', '600', 'normal'),
]
dissolve = uri('assets/img/dissolve.png', 'image/png')
lines = ['/* Generated by tools/make_embedded.py — used only when index.html is opened directly from your computer (file://).',
         '   Online (GitHub Pages) the site loads the normal files instead. Regenerate with: python3 tools/make_embedded.py */',
         'window.RJY_EMBED = {']
lines.append(',\n'.join('  %s: "%s"' % (k, v) for k, v in tex.items()))
lines.append('};')
lines.append('(function () {')
lines.append('  if (!document.fonts || !window.FontFace) return;')
for fam, path, w, st in fonts:
    lines.append('  document.fonts.add(new FontFace(%r, "url(%s)", { weight: %r, style: %r, display: "swap" }));' % (fam, uri(path, 'font/woff2'), w, st))
lines.append('  var css = ".sec--first::before{-webkit-mask-image:url(%s),linear-gradient(#000,#000);mask-image:url(%s),linear-gradient(#000,#000)}";' % (dissolve, dissolve))
lines.append('  var st = document.createElement("style"); st.textContent = css; document.head.appendChild(st);')
lines.append('})();')
(site / 'assets/painting/embedded.js').write_text('\n'.join(lines) + '\n')
print('wrote assets/painting/embedded.js,', (site / 'assets/painting/embedded.js').stat().st_size // 1024, 'KB')
